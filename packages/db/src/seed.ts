/**
 * Demo clinic seed (PRD §20 M0). Produces plain SQL so it can be applied with
 * `wrangler d1 execute --file`. For local and staging only: never production.
 * All names and phone numbers are invented.
 */
import { uuidv7 } from '@yegna/shared';
import {
  DEFAULT_WEEKLY_HOURS,
  addDays,
  fixedHolidays,
  localDateOf,
  localToUtc,
  parseIsoDate,
  toEthiopian,
  weekdayOf,
} from '@yegna/time';

type Row = Record<string, string | number | boolean | null>;

function lit(v: Row[string]): string {
  if (v === null) return 'NULL';
  if (typeof v === 'boolean') return v ? '1' : '0';
  if (typeof v === 'number') return String(v);
  return `'${v.replace(/'/g, "''")}'`;
}

function insert(table: string, rows: Row[]): string[] {
  return rows.map((r) => {
    const cols = Object.keys(r);
    return `INSERT INTO ${table} (${cols.join(', ')}) VALUES (${cols.map((c) => lit(r[c]!)).join(', ')});`;
  });
}

/** Tables in delete order (children first). */
const TABLES = [
  'audit_log',
  'notification_log',
  'import_rows',
  'imports',
  'patient_requests',
  'bookings',
  'patients',
  'procedures',
  'blocks',
  'holidays',
  'day_rules',
  'settings',
  'devices',
  'users',
  'sync_ops',
  'sync_seq',
];

export function buildSeedSql(now: number = Date.now()): string {
  let version = 0;
  const sync = (updatedBy: string | null = null) => ({
    version: ++version,
    updated_at: now,
    updated_by: updatedBy,
    deleted_at: null,
  });

  const doctorId = uuidv7(now);
  const users: Row[] = [
    {
      id: doctorId,
      name: 'ዶ/ር ሰላም (Demo Doctor)',
      role: 'doctor',
      locale: 'am',
      calendar: 'ethiopian',
      ...sync(),
    },
    {
      id: uuidv7(now),
      name: 'ሐና (Demo Staff)',
      role: 'staff',
      locale: 'am',
      calendar: 'ethiopian',
      ...sync(doctorId),
    },
    {
      id: uuidv7(now),
      name: 'Dawit (Demo Staff)',
      role: 'staff',
      locale: 'en',
      calendar: 'gregorian',
      ...sync(doctorId),
    },
  ];

  const procDefs = [
    ['ምርመራ', 'Check-up', 'CK', 30, '#4f86c6'],
    ['ጽዳት', 'Cleaning', 'CL', 45, '#3aa676'],
    ['ሙሌት', 'Filling', 'FL', 60, '#d9a521'],
    ['ነቀላ', 'Extraction', 'EX', 45, '#c8553d'],
    ['የስር ህክምና', 'Root canal', 'RC', 90, '#8e5cc2'],
  ] as const;
  const procedures: Row[] = procDefs.map(([am, en, code, dur, color], i) => ({
    id: uuidv7(now),
    name_am: am,
    name_en: en,
    code,
    duration_min: dur,
    color,
    active: true,
    sort: i,
    ...sync(doctorId),
  }));

  const patientDefs = [
    ['አበበ ከበደ', '+251900000101'],
    ['Tigist Alemu', '+251900000102'],
    ['ሰላማዊት ታደሰ', '+251700000103'],
    ['Yonas Bekele', '+251900000104'],
    ['መሠረት ገብሬ', '+251900000105'],
    ['Hiwot Mengistu', '+251700000106'],
    ['ብርሃኑ ዘውዴ', '+251900000107'],
    ['Liya Tesfaye', '+251900000108'],
  ] as const;
  const patients: Row[] = patientDefs.map(([name, phone]) => ({
    id: uuidv7(now),
    name,
    phone_e164: phone,
    note: null,
    ...sync(doctorId),
  }));

  const today = localDateOf(now);
  const ecYear = toEthiopian(parseIsoDate(today)).year;
  const holidays: Row[] = [...fixedHolidays(ecYear), ...fixedHolidays(ecYear + 1)].map((h) => ({
    id: uuidv7(now),
    date: h.date,
    name_am: h.name_am,
    name_en: h.name_en,
    closed: true,
    ...sync(doctorId),
  }));
  const holidayDates = new Set(holidays.map((h) => h.date as string));

  // Two bookings per open day for the next 7 days; doctor-created, so approved (PRD §10).
  const bookings: Row[] = [];
  let p = 0;
  for (let d = 0; d < 7; d++) {
    const date = addDays(today, d);
    if (!DEFAULT_WEEKLY_HOURS[weekdayOf(date)] || holidayDates.has(date)) continue;
    for (const [startMin, procIdx] of [
      [9 * 60 + 30, 0],
      [14 * 60, 2],
    ] as const) {
      const proc = procedures[procIdx]!;
      bookings.push({
        id: uuidv7(now),
        patient_id: patients[p++ % patients.length]!.id as string,
        procedure_id: proc.id as string,
        start_at: localToUtc(date, startMin),
        duration_min: proc.duration_min as number,
        status: 'approved',
        approved_by: doctorId,
        approved_at: now,
        source: 'app',
        created_by: doctorId,
        ...sync(doctorId),
      });
    }
  }

  const settings: Row[] = [
    {
      id: 'settings',
      weekly_hours: JSON.stringify(DEFAULT_WEEKLY_HOURS),
      unspecified_duration_min: 60,
      patient_reminder_at: 18 * 60,
      doctor_summary_at: 19 * 60,
      default_template: null,
      ...sync(doctorId),
    },
  ];

  return [
    '-- Yegna demo clinic seed. Local/staging only. Generated by packages/db/src/seed.ts',
    ...TABLES.map((t) => `DELETE FROM ${t};`),
    ...insert('users', users),
    ...insert('procedures', procedures),
    ...insert('patients', patients),
    ...insert('holidays', holidays),
    ...insert('settings', settings),
    ...insert('bookings', bookings),
    `INSERT INTO sync_seq (id, value) VALUES (1, ${version});`,
    '',
  ].join('\n');
}
